
# dictionary data type -> = {'key1': 'value1', 'key2': 'value2'}
my_cat = {'size': 'fat', 'color': 'gray', 'sound': 'meow'}
print('My cat has a ' + my_cat['color'] + ' fur.')


# dictionaries can still use integer as keys (but unlike list, it is not needed to start from 0)
spam = {12345: 'Luggage Combination', 42: 'The Answer'}
print(spam[12345])