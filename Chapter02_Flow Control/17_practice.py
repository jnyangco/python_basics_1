# What is the difference between range(10), range(0, 10), and range(0, 10, 1) in a for loop

print('-----------------------')
for i in range(10):
    print(i)

print('-----------------------')
for i in range(0, 10):
    print(i)

print('-----------------------')
for i in range(0, 10, 1):
    print(i)

