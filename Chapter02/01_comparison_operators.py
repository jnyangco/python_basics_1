# ==, !=, <, >, <=, >=

# Boolean -> True or False

# Compare integers
print('=== Compare Integers ===')
print(42 == 42)
print(42 == 99)
print(2 != 3)
print(2 != 2)

# Compare Strings
print('=== Compare Strings ===')
print('cat' == 'cat')
print('cat' == 'dog')


# Compare Boolean values
print('=== Compare Boolean values ===')
print(True == True)
print(False == False)

# Compare other numbers
print('=== Compare other numbers ===')
print(42 == 42.0) #true
print(42 == 44)

# Compare int to string(number)
print('=== Compare int to string(number) ===')
print(50 == '50')