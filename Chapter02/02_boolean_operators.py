# and, or, not

# and -> should satisfy both conditions are True
print('=== and ===')
print(True and True)
print(True and False)

print(False and True)
print(False and False)

# or -> only one True -> then it will be True
print('=== or ===')
print(True or True)
print(True or False)
print(False or True)
print(False or False)

# not
print('=== not ===')
print(not True)
print(not False)